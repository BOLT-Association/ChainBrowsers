// Bundle the trusted identity service (src/identity-service.js + b017 + @bsv/sdk + a Buffer polyfill)
// into one ES module for the Hodos frontend, which runs it in its own identity prompt.
//
//   node scripts/bundle-identity.mjs [out]
//
// Writes dist/bolt-identity.js, and also `out` when given (Hodos keeps a copy at
// frontend/src/vendor/bolt-identity.js, checked in like BoltShimScript.h). Regenerate it whenever
// the identity module, b017 or this script changes.
import { build } from 'esbuild'
import { copyFileSync, mkdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const dist = join(root, 'dist')
mkdirSync(dist, { recursive: true })

const result = await build({
  entryPoints: [join(root, 'src/identity-service.js')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2020',
  inject: [join(here, 'shim-inject.js')],
  legalComments: 'none',
  write: false,
  minify: true
})
const banner = '// GENERATED by ChainBrowsers packages/bolt `npm run bundle:identity` — do not edit.\n/* eslint-disable */\n// @ts-nocheck\n'
const path = join(dist, 'bolt-identity.js')
writeFileSync(path, banner + result.outputFiles[0].text)
console.log(`bolt-identity.js ${Math.round(statSync(path).size / 1024)} KB`)
if (process.argv[2]) {
  const out = resolve(process.argv[2])
  copyFileSync(path, out)
  console.log(`copied to ${out}`)
}
