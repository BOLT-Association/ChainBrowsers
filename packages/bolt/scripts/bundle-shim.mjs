// Bundle the in-page BOLT shim (src/browser.js + b017 + @bsv/sdk + a Buffer polyfill) into one browser
// IIFE, then wrap it as a C++ raw-string header Hodos injects as BOLT_SHIM_SCRIPT.
//
//   node scripts/bundle-shim.mjs
//
// Outputs:
//   dist/bolt-shim.js           the IIFE (global `BoltShim` with installBolt); also usable in a <script>
//   dist/BoltShimScript.h       the same JS as a C++ raw string + a tail that installs window.BOLT
//
// The header is what the browser embeds (see docs/bolt-browser.md). Regenerate it whenever the handler,
// b017 or this script changes; it is a build artifact, checked in for the browser's convenience.
import { build } from 'esbuild'
import { mkdirSync, writeFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const dist = join(root, 'dist')
mkdirSync(dist, { recursive: true })

const result = await build({
  entryPoints: [join(root, 'src/browser.js')],
  bundle: true,
  format: 'iife',
  globalName: 'BoltShim',
  platform: 'browser',
  target: 'es2020',
  inject: [join(here, 'shim-inject.js')],
  legalComments: 'none',
  write: false,
  minify: true
})
const js = result.outputFiles[0].text
const jsPath = join(dist, 'bolt-shim.js')
writeFileSync(jsPath, js)

// The install tail: run inside the page after the bundle defines `BoltShim`. arcadeUrl and the trusted
// issuers come from a small config the browser sets on window before injection (window.__BOLT_CONFIG__),
// defaulting to the local stack so a localhost test page works with no extra wiring.
const tail = `
;(function () {
  try {
    var cfg = (typeof window !== 'undefined' && window.__BOLT_CONFIG__) || {};
    BoltShim.installBolt({
      arcadeUrl: cfg.arcadeUrl || 'http://localhost:8080',
      trustedIssuers: cfg.trustedIssuers || []
    });
  } catch (e) {
    try { console.error('BOLT shim install failed:', e && e.message); } catch (_) {}
  }
})();
`

// A C++ raw-string delimiter that cannot appear in minified JS.
const DELIM = 'BOLTSHIMJS'
const full = js + '\n' + tail
if (full.includes(')' + DELIM + '"')) {
  throw new Error('raw-string delimiter collision; choose another DELIM')
}
// MSVC caps a single string literal at ~16,384 bytes (C2026; measured on VS2022 14.44 — a 16 KB
// literal compiles, 24 KB does not), and the cap also applies to the CONCATENATED result of adjacent
// literals. So emit each chunk as a SEPARATE `const char*` under the cap and join them at runtime.
const CHUNK = 16000
const parts = []
for (let i = 0; i < full.length; i += CHUNK) {
  parts.push(`  R"${DELIM}(${full.slice(i, i + CHUNK)})${DELIM}"`)
}
const header = `// AUTO-GENERATED by packages/bolt/scripts/bundle-shim.mjs — do not edit by hand.
// The in-page BOLT shim (installs window.BOLT over Hodos's wallet_call rail). See docs/bolt-browser.md.
// Split into separate string literals because MSVC caps a (concatenated) literal at 65,535 bytes;
// BoltShimScript() joins them once at first use. Inject with: frame->ExecuteJavaScript(BoltShimScript(), url, 0);
#pragma once
#include <string>

static const char* const BOLT_SHIM_PARTS[] = {
${parts.join(',\n')}
};

inline const std::string& BoltShimScript() {
  static const std::string script = [] {
    std::string s;
    for (const char* part : BOLT_SHIM_PARTS) s += part;
    return s;
  }();
  return script;
}
`
const hPath = join(dist, 'BoltShimScript.h')
writeFileSync(hPath, header)

const kb = (p) => (statSync(p).size / 1024).toFixed(0) + ' KB'
console.log(`bolt-shim.js   ${kb(jsPath)}`)
console.log(`BoltShimScript.h ${kb(hPath)}`)
