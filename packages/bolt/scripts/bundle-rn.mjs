// Bundle the host-app entry (src/rn.js + b017) into one ES module for a React Native app.
//
//   node scripts/bundle-rn.mjs [outFile]      default: dist/bolt-rn.js
//
// `@bsv/sdk` is left as an import: the app has its own (bsv-browser patches it for native crypto),
// and two copies would not share classes. Class private members are lowered (es2020) so the file
// needs nothing of the app's Babel setup. b017 uses the `Buffer` global, which a React Native app
// that installs react-native-quick-crypto (or any Buffer polyfill) already has.
import { build } from 'esbuild'
import { mkdirSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = resolve(process.argv[2] ?? join(root, 'dist', 'bolt-rn.js'))
mkdirSync(dirname(outfile), { recursive: true })
await build({
  entryPoints: [join(root, 'src/rn.js')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  mainFields: ['module', 'main'],
  target: 'es2020',
  external: ['@bsv/sdk'],
  legalComments: 'none',
  banner: { js: '// AUTO-GENERATED by ChainBrowsers packages/bolt/scripts/bundle-rn.mjs — do not edit by hand.\n/* eslint-disable */' },
  outfile
})
console.log(`${outfile}  ${(statSync(outfile).size / 1024).toFixed(0)} KB`)
